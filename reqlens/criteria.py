def criterion_name(cid: str) -> str:
    c = ALL.get(cid)
    return c.name if c else cid


def criteria_prompt_block(scope: str) -> str:
    items = INDIVIDUAL if scope == "requirement" else SET
    lines = []
    for c in items:
        lines.append(f"- `{c.id}` — {c.name} ({c.ref}): {c.definition} Что искать: {c.check}")
    return "\n".join(lines)


def severity_prompt_block() -> str:
    return "\n".join(f"- `{k}` — {v}" for k, v in SEVERITY_DEFINITION.items())
