def _doc_block(doc: Document) -> str:
    return (
        f"=== ДОКУМЕНТ «{doc.title}» ({doc.fmt}, {doc.line_count} строк) ===\n"
        f"{doc.numbered_text()}\n=== КОНЕЦ ДОКУМЕНТА ==="
    )


def _req_index(reqs: Iterable[Requirement]) -> str:
    rows = []
    for r in reqs:
        did = f" [{r.doc_id}]" if r.doc_id else ""
        rows.append(f"- {r.id}{did} (L{r.lines_label}, {r.kind}) — {r.summary}")
    return "\n".join(rows)


def _findings_index(findings: Iterable[Finding]) -> str:
    rows = []
    for f in findings:
        lines = ", ".join(f"L{e.line_start}" for e in f.evidence)
        rows.append(f"- {f.uid} [{f.criterion}/{f.severity}] {f.title} ({lines})")
    return "\n".join(rows) or "- (нет)"


