def review_prompt(doc: Document, reqs: List[Requirement], findings: List[Finding]) -> str:
    items = []
    for f in findings:
        quotes = "; ".join(f"L{e.line_start}: «{e.quote[:140]}»" for e in f.evidence[:3])
        reqs_s = ", ".join(f.req_ids) or "набор"
        items.append(
            f"- id={f.uid} | {f.criterion} | {f.severity} | источник={f.source} | {reqs_s}\n"
            f"  суть: {f.title}\n  объяснение: {f.explanation[:400]}\n  цитаты: {quotes}"
        )
    return f"""Ты — старший ревьюер-скептик. Перед тобой документ и все находки агента. Твоя задача — контроль \
качества отчёта перед выдачей команде.

Для КАЖДОЙ находки верни decision:
- drop — находка ложная: противоречит тексту документа (утверждает отсутствие того, что есть), основана на неверном \
прочтении, это придирка без реального риска или цитаты её не подтверждают;
- merge — дубль другой находки: merge_into — id находки, которую оставляем (с более полным описанием);
- keep — верная находка.
Для keep и merge укажи откалиброванную severity. critical — только то, что блокирует реализацию или тестирование \
ключевой функции либо создаёт риск для денег, данных или безопасности; не завышай и не занижай.
Находки с источник=rule получены детерминированными правилами — удаляй их только при явной ошибке.

Затем:
- priorities — 5–8 действий «что исправить в первую очередь», по убыванию важности; action — одна конкретная \
фраза-поручение; finding_ids — id связанных находок.
- summary — резюме для руководителя, 3–4 предложения: готовность документа и главные риски.
- development_reason и testing_reason — по 1–2 предложения: можно ли начинать разработку и тестирование \
(тест-дизайн) по этому документу и почему.

Шкала критичности:
{severity_prompt_block()}

Требования:
{_req_index(reqs)}

Находки ({len(findings)}):
{chr(10).join(items)}

{_doc_block(doc)}

Верни JSON: {{"decisions": [...], "priorities": [...], "summary": "...", "development_reason": "...", "testing_reason": "..."}}"""
